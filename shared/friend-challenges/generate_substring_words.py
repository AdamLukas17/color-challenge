#!/usr/bin/env python3
"""Regenerate substring-words.txt from badwords-en.txt.

A blocked word is matched *inside* a nickname (e.g. "xxbullshitxx") only if it
never appears inside an ordinary English word, so names like "Annalise",
"Peacock" or "Therapist" aren't blocked. Ordinary words come from the macOS
system dictionary (/usr/share/dict/web2 + propernames). Every other entry is
still matched as a whole word or as the whole (spaced-out) nickname.

Run: python3 generate_substring_words.py   (output is committed; apps don't run this)
"""
import re
LEET = {"0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t", "8": "b", "@": "a", "$": "s", "!": "i", "|": "i", "+": "t"}

def normalize(text):
    out = []
    for ch in text.lower():
        c = LEET.get(ch, ch)
        out.append(c if "a" <= c <= "z" else " ")
    return re.sub(" +", " ", "".join(out)).strip()

entries = set()
for line in open("badwords-en.txt", encoding="utf-8"):
    line = line.rstrip("\n")
    if not line.strip() or line.startswith("#"):
        continue
    compact = normalize(line).replace(" ", "")
    if len(compact) >= 4:
        entries.add(compact)

words = set()
for path in ("/usr/share/dict/web2", "/usr/share/dict/propernames"):
    words |= {w.strip().lower() for w in open(path, encoding="utf-8")}

# Strong words matched inside a nickname even though an old dictionary word
# contains them (e.g. "Scunthorpe"); a rare false positive is the better trade.
ALWAYS = {"cunt", "faggot", "nigga", "nigger", "shit", "slut", "twat", "wank", "whore"}

safe = sorted({e for e in entries if not any(e in w and w != e for w in words)} | (ALWAYS & entries))
with open("substring-words.txt", "w", encoding="utf-8") as f:
    f.write("# Generated by generate_substring_words.py from badwords-en.txt (LDNOOBW, CC BY 4.0).\n")
    f.write("# Normalized entries that are also matched inside a nickname. Do not edit by hand.\n")
    f.write("\n".join(safe) + "\n")
print(len(safe), "substring-safe entries")
